    /// <summary>Retorna a string localizada para a chave informada.</summary>
    public static string Get(string key)
    {
        if (_strings.TryGetValue(IdiomaAtual, out var dict) && dict.TryGetValue(key, out var val))
            return val;
        // Fallback para pt-BR
        if (_strings[Idioma.PtBr].TryGetValue(key, out var fallback))
            return fallback;
        return key;
    }

    public static void DefinirIdioma(Idioma idioma)
    {
        IdiomaAtual = idioma;
        Salvar();
    }

    public static void CarregarPreferencia()
    {
        try
        {
            if (!File.Exists(ArquivoConfig)) return;
            var json = File.ReadAllText(ArquivoConfig);
            using var doc = JsonDocument.Parse(json);
            if (doc.RootElement.TryGetProperty("Idioma", out var el) &&
                Enum.TryParse<Idioma>(el.GetString(), out var idioma))
                IdiomaAtual = idioma;
        }
        catch { }
    }

    private static void Salvar()
    {
        Directory.CreateDirectory(DatabaseService.PastaDados);
        File.WriteAllText(ArquivoConfig,
            JsonSerializer.Serialize(new { Idioma = IdiomaAtual.ToString() }));
    }
